#!/usr/bin/env node
import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

// Turns a directory of per-piece SVG files into one inline <defs> block of
// <symbol>s, and splices it into a shell template between markers.
//
// Shells are self-contained single files with no build step, so the generated
// block is committed alongside the source art rather than assembled at runtime.
// This script exists so swapping or updating a piece set is a regeneration
// rather than a hand-edit of several thousand lines of markup.

const HERE = path.dirname(fileURLToPath(import.meta.url))
const START = '<!-- PIECE-DEFS:START -->'
const END = '<!-- PIECE-DEFS:END -->'
const PIECES = ['wK', 'wQ', 'wR', 'wB', 'wN', 'wP', 'bK', 'bQ', 'bR', 'bB', 'bN', 'bP']

function inner(svg) {
  return svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}

function viewBox(svg) {
  return (/viewBox="([^"]+)"/.exec(svg) ?? [])[1] ?? '0 0 45 45'
}

export async function buildDefs({ dir, prefix }) {
  const files = new Set(await readdir(dir))
  const symbols = []
  for (const piece of PIECES) {
    const name = `${piece}.svg`
    if (!files.has(name)) throw new Error(`Piece set at ${dir} is missing ${name}`)
    const svg = await readFile(path.join(dir, name), 'utf8')
    // Element ids inside an art file collide once twelve of them share one
    // document, and a duplicate id silently repoints every <use> that follows.
    const scoped = inner(svg).replace(/\bid="([^"]+)"/g, `id="${prefix}-${piece}-$1"`)
    symbols.push(`<symbol id="${prefix}-${piece}" viewBox="${viewBox(svg)}">${scoped}</symbol>`)
  }
  return symbols.join('\n')
}

async function main(argv) {
  const { values } = parseArgs({
    args: argv,
    options: {
      set: { type: 'string', default: 'chessnut' },
      prefix: { type: 'string', default: 'pc' },
      into: { type: 'string', multiple: true },
      check: { type: 'boolean', default: false },
    },
  })

  const dir = path.join(HERE, '..', 'assets', 'pieces', values.set)
  const defs = await buildDefs({ dir, prefix: values.prefix })
  const block = [
    START,
    `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" aria-hidden="true" focusable="false" style="position:absolute">`,
    `<defs>`,
    `<!-- Piece set: ${values.set}. Generated by scripts/build-piece-defs.mjs; edit the source art, not this block. -->`,
    defs,
    `</defs></svg>`,
    END,
  ].join('\n')

  const targets = values.into ?? []
  if (!targets.length) {
    process.stdout.write(`${block}\n`)
    return
  }

  let drift = false
  for (const target of targets) {
    const file = path.resolve(target)
    const html = await readFile(file, 'utf8')
    const from = html.indexOf(START)
    const to = html.indexOf(END)
    if (from === -1 || to === -1) throw new Error(`${target} has no ${START} / ${END} markers`)
    const next = html.slice(0, from) + block + html.slice(to + END.length)
    if (next === html) {
      console.error(`${path.basename(file)}: up to date`)
      continue
    }
    drift = true
    if (values.check) {
      console.error(`${path.basename(file)}: OUT OF DATE — re-run without --check`)
      continue
    }
    await writeFile(file, next)
    console.error(`${path.basename(file)}: updated (${(defs.length / 1024).toFixed(0)} KB of symbols)`)
  }
  if (values.check && drift) process.exitCode = 1
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message)
    process.exitCode = 1
  })
}
